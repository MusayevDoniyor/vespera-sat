def clean_synonyms(defn):
    # Extract candidate synonyms from definition
    raw = [w.strip(' ;,."()') for w in defn.split() if len(w) > 3 and w.lower() not in ['something', 'someone', 'having', 'relating', 'causing', 'because', 'without', 'especially', 'between', 'another', 'through', 'toward', 'particular', 'state', 'quality', 'order', 'action']]
    return raw[:4]

def get_pos(word, defn):
    w = word.strip().lower()
    d = defn.strip().lower()
    if any(w.endswith(" " + p) for p in ["in", "to", "on", "with", "about", "toward", "for", "by", "of", "from", "as"]):
        return "phrase"
    if d.startswith("to ") or d.startswith("to not "):
        return "verb"
    if any(d.startswith(ns) for ns in ["the quality", "the act", "a person", "a feeling", "a statement", "an impressive", "the process", "a condition", "a device", "a place", "a great difference", "an assumption", "a sign", "a list", "a temporary relief", "courage", "a disturbance", "a collection", "a scarcity", "lack of", "the rate", "a position", "the ability", "fairness", "honesty", "fertility", "deep respect"]) or w.endswith("ness") or w.endswith("tion") or w.endswith("ity") or w.endswith("ment"):
        return "noun"
    if w.endswith("ly") or d.startswith("in a") or d.startswith("gently") or d.startswith("done quickly") or d.startswith("consistently") or d.startswith("unwillingly"):
        return "adverb"
    return "adjective"

